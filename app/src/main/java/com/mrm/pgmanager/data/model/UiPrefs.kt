package com.mrm.pgmanager.data.model

/**
 * ترجیحاتِ دسترس‌پذیری و حریمِ خصوصی (فاز ۷).
 *
 * چرا جدا از [MonitoringSettings]؟ چون آن‌ها دربارهٔ «چه چیزی را پایش کن» است و
 * این‌ها دربارهٔ «چطور با من رفتار کن». قاطی‌کردن‌شان باعث می‌شد هر تغییرِ ظاهری
 * یک پیکربندیِ پایش را هم جابه‌جا کند.
 *
 * @param hapticsEnabled بازخوردِ لمسی. پیش‌فرض روشن؛ برای کاربرانِ حساس به
 *   لرزش یا گوشی‌های پرلرزش خاموش می‌شود. همهٔ `Haptics.*` همین را می‌خوانند.
 * @param reduceMotion کاهشِ انیمیشن. اگر روشن باشد، اسکیلِ حرکتِ Compose صفر
 *   می‌شود: انیمیشن‌ها حذف می‌شوند، نه فقط کوتاه. (تنظیمِ سیستمیِ «حذفِ
 *   انیمیشن» هم مستقل از این، توسط خودِ Compose رعایت می‌شود.)
 * @param secureScreen جلوگیری از عکسِ‌گرفتن/نمایشِ محتوا در Recents
 *   (`FLAG_SECURE`). پیش‌فرض **روشن** چون اپ توکنِ پنل و لینک‌های اشتراک را
 *   نشان می‌دهد؛ کاربر می‌تواند خاموشش کند.
 */
data class UiPrefs(
    val hapticsEnabled: Boolean = true,
    val reduceMotion: Boolean = false,
    val secureScreen: Boolean = true
)
